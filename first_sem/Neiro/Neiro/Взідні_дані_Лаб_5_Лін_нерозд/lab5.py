# simple MLP implementation (softmax output for multi-class)
def sigmoid(z, alpha=1.0):
    return 1.0 / (1.0 + np.exp(-alpha * z))

def sigmoid_derivative(a, alpha=1.0):
    return alpha * a * (1.0 - a)

def softmax(z):
    e = np.exp(z - np.max(z, axis=1, keepdims=True))
    return e / e.sum(axis=1, keepdims=True)

def to_onehot(y):
    classes = np.unique(y)
    mapping = {v:i for i,v in enumerate(classes)}
    y_idx = np.array([mapping[v] for v in y])
    onehot = np.zeros((len(y), len(classes)))
    onehot[np.arange(len(y)), y_idx] = 1
    return onehot, mapping

# network architecture
n_inputs = Xc_scaled.shape[1]
n_outputs = len(np.unique(yc))
hidden_sizes = MLP_HIDDEN  # list
layers = [n_inputs] + hidden_sizes + [n_outputs]

# weights init
def init_weights(layers, seed=None):
    rng = np.random.RandomState(seed)
    weights = []
    biases = []
    for i in range(len(layers)-1):
        w = rng.normal(scale=0.1, size=(layers[i], layers[i+1]))
        b = np.zeros((1, layers[i+1]))
        weights.append(w)
        biases.append(b)
    return weights, biases

# forward pass
def forward(X, weights, biases, alpha=1.0):
    activations = [X]
    zs = []
    for i in range(len(weights)-1):
        z = activations[-1].dot(weights[i]) + biases[i]
        a = sigmoid(z, alpha=alpha)
        zs.append(z)
        activations.append(a)
    # last layer: linear + softmax
    z = activations[-1].dot(weights[-1]) + biases[-1]
    zs.append(z)
    a = softmax(z)
    activations.append(a)
    return activations, zs

# backprop
def backprop(X, y_onehot, weights, biases, alpha=1.0, lr=0.1):
    activations, zs = forward(X, weights, biases, alpha)
    grads_w = [np.zeros_like(w) for w in weights]
    grads_b = [np.zeros_like(b) for b in biases]

    # output delta (cross-entropy with softmax)
    delta = activations[-1] - y_onehot  # shape (n, n_outputs)
    grads_w[-1] = activations[-2].T.dot(delta) / X.shape[0]
    grads_b[-1] = np.mean(delta, axis=0, keepdims=True)

    # backprop through hidden layers
    for l in range(len(weights)-2, -1, -1):
        da = delta.dot(weights[l+1].T)
        a = activations[l+1]
        delta = da * sigmoid_derivative(a, alpha=alpha)
        grads_w[l] = activations[l].T.dot(delta) / X.shape[0]
        grads_b[l] = np.mean(delta, axis=0, keepdims=True)

    # update weights
    for i in range(len(weights)):
        weights[i] -= lr * grads_w[i]
        biases[i] -= lr * grads_b[i]
    return weights, biases

# training function
def train_mlp(X_train, y_train, layers, epochs=1000, lr=0.1, alpha=1.0, seed=None, verbose=False):
    weights, biases = init_weights(layers, seed=seed)
    y_onehot, mapping = to_onehot(y_train)
    for ep in range(epochs):
        weights, biases = backprop(X_train, y_onehot, weights, biases, alpha=alpha, lr=lr)
        if verbose and (ep % (epochs//5 + 1) == 0):
            activations, _ = forward(X_train, weights, biases, alpha=alpha)
            preds = np.argmax(activations[-1], axis=1)
            acc = np.mean(preds == np.array([list(mapping.keys())[list(mapping.values()).index(i)] for i in preds])) if False else None
            print(f"Epoch {ep}/{epochs}")
    return weights, biases, mapping

