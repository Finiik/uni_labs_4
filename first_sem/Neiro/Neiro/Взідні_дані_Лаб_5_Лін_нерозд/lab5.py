# 3) Competitive Kohonen-like (winner-takes-all) clustering
# ----------------------------
class CompetitiveKohonen:
    def __init__(self, n_units, n_features, lr=0.08, lr_decay=0.995, random_state=None):
        self.n_units = n_units
        self.lr0 = lr
        self.lr_decay = lr_decay
        self.rng = np.random.RandomState(random_state)
        # small random init across normalized space
        self.weights = self.rng.normal(scale=0.1, size=(n_units, n_features))

    def fit(self, X, epochs=200, verbose=False):
        X = np.asarray(X)
        lr = self.lr0
        for ep in range(epochs):
            idxs = np.arange(X.shape[0])
            self.rng.shuffle(idxs)
            for i in idxs:
                x = X[i]
                dists = np.linalg.norm(self.weights - x, axis=1)
                w = int(np.argmin(dists))
                self.weights[w] += lr * (x - self.weights[w])
            lr *= self.lr_decay
            if verbose and (ep % (epochs//5 + 1) == 0):
                print(f"Epoch {ep}/{epochs} lr={lr:.4f}")
        return self

    def predict(self, X):
        dists = np.linalg.norm(self.weights[None,:,:] - X[:,None,:], axis=2)
        labels = np.argmin(dists, axis=1)
        return labels

