def classical_threshold_clustering(X, T):
    X = np.asarray(X)
    centers = []
    labels = -1 * np.ones(X.shape[0], dtype=int)
    cluster_counts = []
    for i, x in enumerate(X):
        if len(centers) == 0:
            centers.append(x.copy())
            labels[i] = 0
            cluster_counts.append(1)
            continue
        dists = np.linalg.norm(np.vstack(centers) - x, axis=1)
        jmin = int(np.argmin(dists))
        if dists[jmin] <= T:
            c = cluster_counts[jmin]
            centers[jmin] = (centers[jmin] * c + x) / (c + 1)
            cluster_counts[jmin] += 1
            labels[i] = jmin
        else:
            centers.append(x.copy())
            cluster_counts.append(1)
            labels[i] = len(centers) - 1
    centers = np.vstack(centers)
    return labels, centers

