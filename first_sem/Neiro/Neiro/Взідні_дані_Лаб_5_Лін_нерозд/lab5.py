def kmeans_with_init_strategy(X, n_clusters, strategy="random", repeats=10, random_state=None):
    rng = np.random.RandomState(random_state)
    n = X.shape[0]
    results = []
    for r in range(repeats):
        if strategy == "first_p":
            if n_clusters > n:
                raise ValueError("n_clusters > n")
            init_idx = np.arange(n_clusters)
            init = X[init_idx]
            km = KMeans(n_clusters=n_clusters, init=init, n_init=1, random_state=rng.randint(0,1e6))
        elif strategy == "nearby_p":
            base = rng.randint(0, n)
            d = np.linalg.norm(X - X[base], axis=1)
            init_idx = np.argsort(d)[:n_clusters]
            init = X[init_idx]
            km = KMeans(n_clusters=n_clusters, init=init, n_init=1, random_state=rng.randint(0,1e6))
        elif strategy == "random":
            init_idx = rng.choice(n, size=n_clusters, replace=False)
            init = X[init_idx]
            km = KMeans(n_clusters=n_clusters, init=init, n_init=1, random_state=rng.randint(0,1e6))
        else:
            raise ValueError("Unknown strategy")
        km.fit(X)
        labels = km.labels_
        inertia = km.inertia_
        sil = None
        try:
            if 1 < n_clusters < n:
                sil = silhouette_score(X, labels)
        except Exception:
            sil = None
        results.append({"labels": labels, "centers": km.cluster_centers_, "inertia": inertia, "silhouette": sil, "init_idx": init_idx})
    return results

