import matplotlib.pyplot as plt

# Вхідні дані з нашої таблиці
d = [100, 250, 500, 750]          # Відстань у метрах
P_T = [-9.1, -1.2, 4.9, 8.4]      # Потужність у дБВт

# Налаштування розміру графіка (ширина, висота в дюймах)
plt.figure(figsize=(8, 5))

# Побудова графіка: маркер 'o' (крапки), лінія '-', синій колір 'b'
plt.plot(d, P_T, marker='o', linestyle='-', color='#1f77b4', linewidth=2, markersize=8)

# Додавання назви та підписів осей
plt.title('Залежність необхідної вихідної потужності від відстані', fontsize=14, pad=15)
plt.xlabel('Відстань d, м', fontsize=12)
plt.ylabel('Потужність P_T, дБВт', fontsize=12)

# Увімкнення сітки для кращої читабельності
plt.grid(True, linestyle='--', alpha=0.7)

# Встановлення меж осей (щоб графік виглядав охайніше)
plt.xlim(0, 850)

# Цей рядок зберігає графік як картинку високої якості (можеш розкоментувати, якщо треба)
# plt.savefig('graph.png', dpi=300, bbox_inches='tight')

# Відображення графіка на екрані
plt.show()