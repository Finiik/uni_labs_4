# 1) Classical simple clustering algorithm (threshold-based)
# ----------------------------
def classical_threshold_clustering(X, T):
    """
    Simple one-pass clustering:
    - first point becomes center of first cluster
    - for each next point, compute distance to each existing center,
      if min distance <= T -> add to that cluster (and update center)
      else create new cluster with center = the point
    Returns: labels array, centers list
    """
    X = np.asarray(X)
    centers = []
    labels = -1 * np.ones(X.shape[0], dtype=int)
    cluster_counts = []
    for i, x in enumerate(X):
        if len(centers) == 0:
            centers.append(x.copy())
            labels[i] = 0
            cluster_counts.append(1)
            continue
        dists = np.linalg.norm(np.vstack(centers) - x, axis=1)
        jmin = np.argmin(dists)
        if dists[jmin] <= T:
            # assign to cluster jmin and update center (running average)
            c = cluster_counts[jmin]
            centers[jmin] = (centers[jmin] * c + x) / (c + 1)
            cluster_counts[jmin] += 1
            labels[i] = jmin
        else:
            # new cluster
            centers.append(x.copy())
            cluster_counts.append(1)
            labels[i] = len(centers) - 1
    centers = np.vstack(centers)
    return labels, centers

