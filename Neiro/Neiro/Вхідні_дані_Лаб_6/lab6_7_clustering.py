def kmeans_with_init_strategy(X, n_clusters, strategy="random", repeat=1, random_state=None):
    """
    Strategies:
      - "first_p": choose first p points as init centers
      - "random": random selection of p points from dataset (scikit-learn default)
      - "nearby_p": pick a random point, then pick p points nearest to it (simulates choosing p points from one cluster)
    Returns a list of results per repeat:
      {"labels":..., "inertia":..., "silhouette":..., "centers":..., "init_idx":...}
    """
    results = []
    rng = np.random.RandomState(random_state)
    n = X.shape[0]
    for r in range(repeat):
        if strategy == "first_p":
            init_idx = list(range(n_clusters))
            init = X[init_idx]
            km = KMeans(n_clusters=n_clusters, init=init, n_init=1, random_state=rng.randint(0,1e6))
        elif strategy == "nearby_p":
            base = rng.randint(0, n)
            # compute distances in original scaled space
            d = np.linalg.norm(X - X[base], axis=1)
            init_idx = np.argsort(d)[:n_clusters]
            init = X[init_idx]
            km = KMeans(n_clusters=n_clusters, init=init, n_init=1, random_state=rng.randint(0,1e6))
        elif strategy == "random":
            # let sklearn pick randomly; but to make deterministic, pick random sample centers
            init_idx = rng.choice(n, size=n_clusters, replace=False)
            init = X[init_idx]
            km = KMeans(n_clusters=n_clusters, init=init, n_init=1, random_state=rng.randint(0,1e6))
        else:
            raise ValueError("Unknown strategy")
        km.fit(X)
        labels = km.labels_
        inertia = km.inertia_
        sil = None
        if 1 < n_clusters < n:
            try:
                sil = silhouette_score(X, labels)
            except Exception:
                sil = None
        results.append({
            "labels": labels,
            "centers": km.cluster_centers_,
            "inertia": inertia,
            "silhouette": sil,
            "init_idx": init_idx
        })
    return results

