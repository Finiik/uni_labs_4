# 3) Neural network clustering (competitive learning / Kohonen-like very small SOM)
# ----------------------------
class CompetitiveKohonen:
    def __init__(self, n_units=3, n_features=None, lr=0.1, lr_decay=0.995, random_state=None):
        self.n_units = n_units
        self.lr0 = lr
        self.lr_decay = lr_decay
        self.random_state = np.random.RandomState(random_state)
        if n_features is None:
            raise ValueError("n_features required")
        # initialize weights randomly (small)
        self.weights = self.random_state.normal(scale=0.1, size=(n_units, n_features))

    def fit(self, X, epochs=100, verbose=False):
        X = np.asarray(X)
        lr = self.lr0
        # optionally normalize inputs for direction-based learning
        for ep in range(epochs):
            idxs = np.arange(X.shape[0])
            self.random_state.shuffle(idxs)
            for i in idxs:
                x = X[i]
                # find winner (closest by Euclidean)
                dists = np.linalg.norm(self.weights - x, axis=1)
                w = np.argmin(dists)
                # update winner weights towards x (Oja-like/simple)
                self.weights[w] += lr * (x - self.weights[w])
            lr *= self.lr_decay
            if verbose and (ep % (epochs//5 + 1) == 0):
                print(f"Epoch {ep}/{epochs} lr={lr:.4f}")
        return self

    def predict(self, X):
        d = np.linalg.norm(self.weights[None,:,:] - X[:,None,:], axis=2)  # shape n_samples x n_units
        labels = np.argmin(d, axis=1)
        return labels

